#!/usr/bin/env bash
# Generate the launchd daemons from config/node.env and (un)load them.
#
#   sudo scripts/30-services.sh install [service...]    write plists + bootstrap
#   sudo scripts/30-services.sh uninstall [service...]  bootout + remove plists
#   scripts/30-services.sh render DIR                    write plists to DIR only (review / test)
#
# Services: nethermind, teku | lighthouse (CL_CLIENT), validator (VALIDATOR_ENABLED),
# listener (LISTENER_ENABLED). Without arguments: all enabled ones.
#
# Plists are generated, not committed: paths, ports and users come from the
# config, so the config is the single source of truth. Every key is explained
# in docs/04-services.md.

source "$(dirname "$0")/lib.sh"
load_config

# One value for every service. In a system daemon NumberOfFiles also sets the
# kernel-wide kern.maxfiles / kern.maxfilesperproc, so services with different
# values would overwrite each other (man launchd.plist).
MAX_FILES=524288

xml_escape() { local s="$1"; s="${s//&/&amp;}"; s="${s//</&lt;}"; s="${s//>/&gt;}"; printf '%s' "$s"; }

# write_plist FILE LABEL KEEPALIVE EXIT_TIMEOUT WORKDIR ENV_PAIRS -- ARGS...
#   KEEPALIVE: always | on-failure
#   ENV_PAIRS: "K=V;K=V" or ""
write_plist() {
  local file="$1" lbl="$2" keepalive="$3" exit_timeout="$4" workdir="$5" envs="$6"
  shift 7 # also drops the "--"
  {
    cat <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by domovina-gnosis-node scripts/30-services.sh. Do not edit; change config/node.env and re-run. -->
<plist version="1.0">
<dict>
  <key>Label</key><string>$lbl</string>
  <key>UserName</key><string>$SERVICE_USER</string>
  <key>GroupName</key><string>$SERVICE_USER</string>
  <key>ProgramArguments</key>
  <array>
EOF
    local a
    for a in "$@"; do printf '    <string>%s</string>\n' "$(xml_escape "$a")"; done
    echo '  </array>'
    echo "  <key>WorkingDirectory</key><string>$workdir</string>"
    if [[ -n "$envs" ]]; then
      echo '  <key>EnvironmentVariables</key>'
      echo '  <dict>'
      local IFS=';' pair
      for pair in $envs; do
        printf '    <key>%s</key><string>%s</string>\n' "${pair%%=*}" "$(xml_escape "${pair#*=}")"
      done
      echo '  </dict>'
    fi
    echo '  <key>RunAtLoad</key><true/>'
    if [[ "$keepalive" == "always" ]]; then
      echo '  <key>KeepAlive</key><true/>'
    else
      echo '  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>'
    fi
    cat <<EOF
  <key>ThrottleInterval</key><integer>30</integer>
  <key>ExitTimeOut</key><integer>$exit_timeout</integer>
  <key>ProcessType</key><string>Standard</string>
  <key>SoftResourceLimits</key><dict><key>NumberOfFiles</key><integer>$MAX_FILES</integer></dict>
  <key>HardResourceLimits</key><dict><key>NumberOfFiles</key><integer>$MAX_FILES</integer></dict>
  <key>StandardOutPath</key><string>/dev/null</string>
  <key>StandardErrorPath</key><string>$LOG_DIR/$(basename "$file" .plist | sed "s/^$LABEL_PREFIX.//").stderr.log</string>
</dict>
</plist>
EOF
  } > "$file"
}

# Teku's launcher is a shell script. launchd runs java directly instead (a
# daemon that is a shell script can be blocked by Background Task Management
# on macOS 26), with the JVM options copied from the launcher of the
# installed version so they follow upgrades.
teku_java_cmd() {
  local heap="$1" home="$GNOSIS_ROOT/teku/current" line
  line="$(sed -n "s/^DEFAULT_JVM_OPTS='\(.*\)'\$/\1/p" "$home/bin/teku" 2>/dev/null || true)"
  [[ -n "$line" ]] || { is_test && line='"-Dteku.home=$APP_HOME"'; }
  [[ -n "$line" ]] || die "cannot read JVM options from $home/bin/teku (is teku installed?)"
  line="${line//\$APP_HOME/$home}"
  eval "JVM_OPTS=($line)"
  TEKU_CMD=("$GNOSIS_ROOT/jre/current/Contents/Home/bin/java" "-Xmx$heap" "${JVM_OPTS[@]}"
            -cp "$home/lib/*" tech.pegasys.teku.Teku)
}

render_service() {
  local svc="$1" dir="$2" file
  file="$dir/$(label "$svc").plist"
  case "$svc" in
    nethermind)
      # Nethermind is a .NET single-file bundle that extracts native libraries
      # on start. The service user's home is /var/empty (read-only), so give it
      # a writable home and extraction dir, or it exits with code 159.
      write_plist "$file" "$(label nethermind)" always 180 "$DATA_DIR/nethermind" \
        "HOME=$GNOSIS_ROOT/state/nethermind;DOTNET_BUNDLE_EXTRACT_BASE_DIR=$GNOSIS_ROOT/state/nethermind/dotnet-bundle" -- \
        "$GNOSIS_ROOT/nethermind/current/nethermind" \
        -c gnosis \
        -dd "$DATA_DIR/nethermind" \
        --Init.LogDirectory "$LOG_DIR/nethermind" \
        --JsonRpc.Enabled true \
        --JsonRpc.Host 127.0.0.1 \
        --JsonRpc.Port "$EL_HTTP_PORT" \
        --Init.WebSocketsEnabled true \
        --JsonRpc.WebSocketsPort "$EL_WS_PORT" \
        --JsonRpc.EnabledModules "[Eth,Net,Web3,Subscribe,Health]" \
        --JsonRpc.EngineHost 127.0.0.1 \
        --JsonRpc.EnginePort "$EL_ENGINE_PORT" \
        --JsonRpc.JwtSecretFile "$JWT_FILE" \
        --HealthChecks.Enabled true \
        --Pruning.CacheMb "$NM_CACHE_MB" \
        --FlatDb.Enabled "$NM_FLATDB" \
        --Network.MaxActivePeers "$NM_MAX_PEERS" \
        --Network.P2PPort "$EL_P2P_PORT" \
        --Network.DiscoveryPort "$EL_P2P_PORT"
      ;;
    teku)
      teku_java_cmd "$TEKU_HEAP"
      local extra=()
      [[ -n "$FEE_RECIPIENT" ]] && extra+=("--validators-proposer-default-fee-recipient=$FEE_RECIPIENT")
      write_plist "$file" "$(label teku)" always 120 "$DATA_DIR/teku" "" -- \
        "${TEKU_CMD[@]}" \
        --network=gnosis \
        --data-base-path="$DATA_DIR/teku" \
        --checkpoint-sync-url="$CHECKPOINT_SYNC_URL" \
        --ee-endpoint="http://127.0.0.1:$EL_ENGINE_PORT" \
        --ee-jwt-secret-file="$JWT_FILE" \
        --rest-api-enabled=true \
        --rest-api-interface=127.0.0.1 \
        --rest-api-port="$CL_HTTP_PORT" \
        --p2p-port="$CL_P2P_PORT" \
        --p2p-quic-port="${CL_QUIC_PORT:-9001}" \
        --p2p-peer-upper-bound="$CL_MAX_PEERS" \
        --p2p-nat-method=NONE \
        --metrics-enabled=true \
        --metrics-interface=127.0.0.1 \
        --metrics-port="$CL_METRICS_PORT" \
        --log-destination=FILE \
        --log-file="$LOG_DIR/teku/teku.log" \
        ${extra[@]+"${extra[@]}"}
      ;;
    lighthouse)
      local extra=()
      [[ -n "$FEE_RECIPIENT" ]] && extra+=(--suggested-fee-recipient "$FEE_RECIPIENT")
      write_plist "$file" "$(label lighthouse)" always 120 "$DATA_DIR/lighthouse" "" -- \
        "$GNOSIS_ROOT/lighthouse/current/lighthouse" bn \
        --network gnosis \
        --datadir "$DATA_DIR/lighthouse" \
        --checkpoint-sync-url "$CHECKPOINT_SYNC_URL" \
        --execution-endpoint "http://127.0.0.1:$EL_ENGINE_PORT" \
        --execution-jwt "$JWT_FILE" \
        --http --http-address 127.0.0.1 --http-port "$CL_HTTP_PORT" \
        --port "$CL_P2P_PORT" \
        --target-peers "$CL_MAX_PEERS" \
        --disable-upnp \
        --metrics --metrics-address 127.0.0.1 --metrics-port "$CL_METRICS_PORT" \
        --logfile-dir "$LOG_DIR/lighthouse" \
        ${extra[@]+"${extra[@]}"}
      ;;
    validator)
      [[ "$FEE_RECIPIENT" =~ ^0x[0-9a-fA-F]{40}$ ]] || die "FEE_RECIPIENT must be set to a 0x address before enabling the validator"
      teku_java_cmd 2g
      write_plist "$file" "$(label validator)" always 60 "$DATA_DIR/validator" "" -- \
        "${TEKU_CMD[@]}" validator-client \
        --network=gnosis \
        --data-base-path="$DATA_DIR/validator" \
        --beacon-node-api-endpoint="http://127.0.0.1:$CL_HTTP_PORT" \
        --validator-keys="$GNOSIS_ROOT/validator/keys:$GNOSIS_ROOT/validator/passwords" \
        --validators-proposer-default-fee-recipient="$FEE_RECIPIENT" \
        --validators-graffiti="$GRAFFITI" \
        --doppelganger-detection-enabled=true \
        --metrics-enabled=true \
        --metrics-interface=127.0.0.1 \
        --metrics-port=8009 \
        --log-destination=FILE \
        --log-file="$LOG_DIR/validator/validator.log"
      ;;
    listener)
      write_plist "$file" "$(label listener)" on-failure 15 "$GNOSIS_ROOT/listener" \
        "STATE_FILE=$GNOSIS_ROOT/state/listener-state.json;WATCHLIST_FILE=$ETC_DIR/watchlist.json;LOG_FILE=$LOG_DIR/listener.log;PID_FILE=$GNOSIS_ROOT/state/listener.pid;RPC_HTTP_URL=http://127.0.0.1:$EL_HTTP_PORT;RPC_WS_URL=ws://127.0.0.1:$EL_WS_PORT" -- \
        "$GNOSIS_ROOT/node/current/bin/node" \
        "--env-file=$ETC_DIR/listener.env" \
        "$GNOSIS_ROOT/listener/listener.mjs"
      ;;
    *) die "unknown service: $svc" ;;
  esac
  plutil -lint "$file" >/dev/null || die "invalid plist generated: $file"
  echo "$file"
}

enabled_services() {
  local s=(nethermind "$CL_CLIENT")
  [[ "$VALIDATOR_ENABLED" == "true" ]] && s+=(validator)
  [[ "$LISTENER_ENABLED" == "true" ]] && s+=(listener)
  echo "${s[@]}"
}

# Directories the services write into, owned by the service user.
prepare_dirs() {
  local svc="$1" d
  for d in "$DATA_DIR/$svc" "$LOG_DIR/$svc" "$GNOSIS_ROOT/state/$svc"; do
    mkdir -p "$d"; svc_own "$d"; chmod 750 "$d"
  done
}

cmd="${1:-}"; shift || true
case "$cmd" in
  render)
    out="${1:?usage: $0 render DIR}"; shift
    mkdir -p "$out"
    services=("$@"); [[ ${#services[@]} -gt 0 ]] || services=($(enabled_services))
    for s in "${services[@]}"; do render_service "$s" "$out"; done
    ;;
  install)
    require_root
    services=("$@"); [[ ${#services[@]} -gt 0 ]] || services=($(enabled_services))
    for s in "${services[@]}"; do
      log "service $s"
      prepare_dirs "$s"
      f="$(render_service "$s" "$LAUNCHD_DIR")"
      chown root:wheel "$f"; chmod 644 "$f"
      launchctl bootout "system/$(label "$s")" 2>/dev/null && info "stopped running instance" || true
      launchctl enable "system/$(label "$s")"
      # bootstrap right after bootout can fail with "5: Input/output error"
      # while launchd is still tearing the old job down; retry briefly.
      for try in 1 2 3 4 5; do
        launchctl bootstrap system "$f" 2>/dev/null && break
        [[ $try -eq 5 ]] && die "launchctl bootstrap failed for $f (see: sudo launchctl print system/$(label "$s"))"
        sleep 2
      done
      info "loaded $f"
    done
    echo
    info "macOS may show an 'Allow in the Background' notification per daemon. Allow it in"
    info "System Settings > General > Login Items & Extensions, then check: scripts/gnosisctl status"
    ;;
  uninstall)
    require_root
    services=("$@"); [[ ${#services[@]} -gt 0 ]] || services=(validator listener lighthouse teku nethermind)
    for s in "${services[@]}"; do
      f="$LAUNCHD_DIR/$(label "$s").plist"
      [[ -f "$f" ]] || continue
      log "removing $s (waits for a clean shutdown)"
      launchctl bootout "system/$(label "$s")" 2>/dev/null || true
      rm -f "$f"
    done
    ;;
  *)
    sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'
    exit 1
    ;;
esac
